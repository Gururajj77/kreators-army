import { useEffect, useMemo, useRef, useState, type CSSProperties, type ReactNode } from 'react';
import { motionOk } from '../../lib/motionOk';
import { FAR } from './art-far';
import { SKYLINE, SKYLINE_HAZE, SKYLINE_MIDS } from './art-skyline';
import './paint.css';
import '../../styles/street.css';

// The street, lazy (visual §1.3): a quiet backdrop, noticed second. The light wrapper the pages use is Street (./Street.tsx), which reserves the box and
// loads this module after first paint and idle. The footer's skyline needs only ./art-skyline (this chunk, street-far); the hero, band and 404 also fetch
// ./art-full (street-full): the shopfront row and the footpath. The scene is still: no pointer depth, no glow, no props. The only motion is the footer
// train's one slow pass. The art is static markup generated by scripts/street-art.mjs and injected as is (V2-SPEC 8.4 documents this one exception).

export type StreetVariant = 'hero' | 'band' | 'skyline';
export type StreetTime = 'auto' | 'day' | 'night';

type Full = typeof import('./art-full');
let fullArt: Full | null = null;
const loadFull = () => import('./art-full').then((m) => (fullArt = m));

/** The markup for one scene. */
function markup(variant: StreetVariant, full: Full | null): string {
  const sky = '<div class="street-sky"></div>';
  // The footer keeps its own fuller night skyline (art-skyline, painted in paint.css); the heroes keep the quiet far layer. Round 11: the footer's
  // landscape is three deep, back to front: the far city (rising toward the band's buttons), the middle distance, then the skyline and its train.
  if (variant === 'skyline') return sky + SKYLINE_HAZE + SKYLINE_MIDS + SKYLINE;
  if (!full) return sky + FAR;
  return sky + FAR + full.MID + full.NEAR;
}

export interface StreetArtProps {
  variant: StreetVariant;
  /** 'auto' follows the theme (a .band-dark ancestor forces night); 'day' or 'night' fixes it. */
  time?: StreetTime;
  /** Skyline: the train crosses once each time this value changes (the footer passes the path: once per page view). */
  cue?: string;
}

/** The art box: the sky and the layers. Absolutely positioned to fill its .street-host; aria-hidden; never focusable. */
export function StreetArt({ variant, time = 'auto', cue }: StreetArtProps) {
  const ref = useRef<HTMLDivElement>(null);
  const [full, setFull] = useState<Full | null>(fullArt);
  const [shown, setShown] = useState(false);
  const needsFull = variant !== 'skyline';
  const ready = !needsFull || full !== null;

  useEffect(() => {
    if (!needsFull || full) return;
    let on = true;
    loadFull()
      .then((m) => on && setFull(m))
      .catch(() => {
        // The far layer alone still reads as a street; a lost chunk costs the shopfronts only.
      });
    return () => {
      on = false;
    };
  }, [needsFull, full]);

  const html = useMemo(() => (ready ? markup(variant, full) : ''), [ready, variant, full]);

  // Fade in over 400 ms once painted (instant under still).
  useEffect(() => {
    if (!ready) return;
    const raf = requestAnimationFrame(() => setShown(true));
    return () => cancelAnimationFrame(raf);
  }, [ready]);

  // The footer's one ambient pass: the train crosses once when the skyline first comes into view on this page view. Never under still. The
  // landscape is tall (it rises to the band's buttons), so the watch is on the base layer that carries the viaduct, at half in view: the train
  // starts when its track is on screen.
  useEffect(() => {
    const el = ref.current;
    if (variant !== 'skyline' || !ready || !el) return;
    el.removeAttribute('data-train');
    const base = el.querySelector('.street-far') ?? el;
    const io = new IntersectionObserver(
      ([e]) => {
        if (!e?.isIntersecting) return;
        io.disconnect();
        if (motionOk() && document.visibilityState !== 'hidden') requestAnimationFrame(() => el.setAttribute('data-train', ''));
      },
      { threshold: base === el ? 0.2 : 0.5 },
    );
    io.observe(base);
    return () => io.disconnect();
  }, [variant, ready, cue]);

  return (
    <div
      ref={ref}
      className="street"
      data-variant={variant}
      data-time={time === 'auto' ? undefined : time}
      data-ready={shown ? '' : undefined}
      aria-hidden="true"
      // Static, generated markup only (scripts/street-art.mjs): no visitor or admin text ever reaches it.
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
}

export interface StreetSceneProps extends StreetArtProps {
  /** --street-h. Defaults: see styles/cast.css (.street-host). */
  height?: string;
  /** The stage: things standing on the footpath, positioned with --floor-front and --floor-back. */
  children?: ReactNode;
  className?: string;
  style?: CSSProperties;
}

/** The whole scene with its stage, for a page that has already loaded this chunk. Pages normally use Street, which loads it lazily. */
export function StreetScene({ variant, time, height, cue, children, className, style }: StreetSceneProps) {
  return (
    <div className={className ? `street-host ${className}` : 'street-host'} data-variant={variant} style={{ ...(height ? { '--street-h': height } : null), ...style } as CSSProperties}>
      <StreetArt variant={variant} time={time} cue={cue} />
      {children && <div className="street-stage">{children}</div>}
    </div>
  );
}
