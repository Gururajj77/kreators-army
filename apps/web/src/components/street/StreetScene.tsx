import { useEffect, useId, useMemo, useRef, useState, type CSSProperties, type ReactNode } from 'react';
import { motionOk } from '../../lib/motionOk';
import { FAR } from './art-far';
import './paint.css';
import '../../styles/street.css';

// The street, lazy (visual §1.3, motion M4): the art and the footer train's one pass. The light wrapper the pages use is Street (./Street.tsx), which
// reserves the box and loads this module after first paint and idle. The skyline needs only ./art-far (this chunk, street-far); the hero, band and
// 404 also fetch ./art-full (street-full), which brings ./motion: the pointer depth, the glow and the shop that wakes. The art is static markup
// generated by scripts/street-art.mjs and injected as is (V2-SPEC 8.4 documents this one exception).

export type StreetVariant = 'hero' | 'band' | 'skyline';
export type StreetTime = 'auto' | 'day' | 'night';

type Full = typeof import('./art-full');
let fullArt: Full | null = null;
const loadFull = () => import('./art-full').then((m) => (fullArt = m));

const MOON = '<svg viewBox="-40 -40 80 80" aria-hidden="true" focusable="false"><path d="M 10 -26 A 28 28 0 1 0 22 18 A 22 22 0 1 1 10 -26 Z"/></svg>';

/** The markup for one scene. Clip ids are prefixed per instance, so two scenes on a page never share one. */
function markup(variant: StreetVariant, full: Full | null, prefix: string): string {
  const sky = '<div class="street-sky"></div>';
  if (variant === 'skyline' || !full) return sky + FAR;
  const mid = full.MID.replace(/id="(aw|dr)/g, `id="${prefix}$1`).replace(/url\(#(aw|dr)/g, `url(#${prefix}$1`);
  return (
    sky +
    `<div class="street-layer street-celestial">${full.STARS}<span class="street-sun"></span><span class="street-moon">${MOON}</span></div>` +
    FAR +
    mid +
    '<div class="street-glow"></div>' +
    full.NEAR
  );
}

export interface StreetArtProps {
  variant: StreetVariant;
  /** 'auto' follows the theme (a .band-dark ancestor forces night); 'day' or 'night' fixes it. */
  time?: StreetTime;
  /** The shutter of the shop nearest the pointer rolls up. Default true for hero and band. */
  wake?: boolean;
  /** Skyline: the train crosses once each time this value changes (the footer passes the path: once per page view). */
  cue?: string;
}

/** The art box: the sky, the layers, the glow. Absolutely positioned to fill its .street-host; aria-hidden; never focusable. */
export function StreetArt({ variant, time = 'auto', wake = variant !== 'skyline', cue }: StreetArtProps) {
  const ref = useRef<HTMLDivElement>(null);
  const prefix = `s${useId().replace(/[^a-zA-Z0-9]/g, '')}`;
  const [full, setFull] = useState<Full | null>(fullArt);
  const [shown, setShown] = useState(false);
  const needsFull = variant !== 'skyline';
  const ready = !needsFull || full !== null;

  useEffect(() => {
    if (!needsFull || full) return;
    let on = true;
    loadFull()
      .then((m) => on && setFull(m))
      .catch(() => {
        // The far layer alone still reads as a street; a lost chunk costs the shopfronts only.
      });
    return () => {
      on = false;
    };
  }, [needsFull, full]);

  const html = useMemo(() => (ready ? markup(variant, full, prefix) : ''), [ready, variant, full, prefix]);

  // Fade in over 400 ms once painted (instant under still).
  useEffect(() => {
    if (!ready) return;
    const raf = requestAnimationFrame(() => setShown(true));
    return () => cancelAnimationFrame(raf);
  }, [ready]);

  // The pointer, glow and wake code comes with the full drawing (./motion, re-exported by ./art-full): the skyline never downloads it.
  useEffect(() => {
    const el = ref.current;
    if (!ready || !el || variant === 'skyline' || !full) return;
    return full.animate(el, { wake }).stop;
  }, [ready, variant, wake, full]);

  // The footer's one ambient pass: the train crosses once when the skyline first comes into view on this page view. Never under still.
  useEffect(() => {
    const el = ref.current;
    if (variant !== 'skyline' || !ready || !el) return;
    el.removeAttribute('data-train');
    const io = new IntersectionObserver(
      ([e]) => {
        if (!e?.isIntersecting) return;
        io.disconnect();
        if (motionOk() && document.visibilityState !== 'hidden') requestAnimationFrame(() => el.setAttribute('data-train', ''));
      },
      { threshold: 0.2 },
    );
    io.observe(el);
    return () => io.disconnect();
  }, [variant, ready, cue]);

  return (
    <div
      ref={ref}
      className="street"
      data-variant={variant}
      data-time={time === 'auto' ? undefined : time}
      data-ready={shown ? '' : undefined}
      aria-hidden="true"
      // Static, generated markup only (scripts/street-art.mjs): no visitor or admin text ever reaches it.
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
}

export interface StreetSceneProps extends StreetArtProps {
  /** --street-h. Defaults: hero clamp(280px, 40vh, 380px); band 300px (230 on phones); skyline 260px. */
  height?: string;
  /** The stage: things standing on the footpath, positioned with --floor-front and --floor-back. */
  children?: ReactNode;
  className?: string;
  style?: CSSProperties;
}

/** The whole scene with its stage, for a page that has already loaded this chunk. Pages normally use Street, which loads it lazily. */
export function StreetScene({ variant, time, height, wake, cue, children, className, style }: StreetSceneProps) {
  return (
    <div className={className ? `street-host ${className}` : 'street-host'} data-variant={variant} style={{ ...(height ? { '--street-h': height } : null), ...style } as CSSProperties}>
      <StreetArt variant={variant} time={time} wake={wake} cue={cue} />
      {children && <div className="street-stage">{children}</div>}
    </div>
  );
}
